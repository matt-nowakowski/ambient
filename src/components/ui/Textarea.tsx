import React from "react";

interface TextareaProps
  extends React.TextareaHTMLAttributes<HTMLTextAreaElement> {
  variant?: "default" | "compact";
}

export const Textarea: React.FC<TextareaProps> = ({
  className = "",
  variant = "default",
  ...props
}) => {
  const baseClasses =
    "px-2 py-1 text-ui bg-glass-strong border-[0.5px] border-glass-edge shadow-card rounded-control text-start transition-all duration-150 placeholder:text-ink-3 hover:border-line-strong focus:outline-none focus:border-ink-3 focus:ring-4 focus:ring-logo-primary/[0.07] resize-y";

  const variantClasses = {
    default: "px-3 py-2 min-h-[100px]",
    compact: "px-2 py-1 min-h-[80px]",
  };

  return (
    <textarea
      className={`${baseClasses} ${variantClasses[variant]} ${className}`}
      {...props}
    />
  );
};
